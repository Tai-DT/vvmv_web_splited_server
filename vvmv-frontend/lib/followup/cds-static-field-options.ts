export const CDS_STATIC_FIELD_KEYS = new Set<CdsFieldKey>(
	Object.keys(CDS_STATIC_FIELD_OPTIONS) as CdsFieldKey[],
);

const CDS_STATIC_ALLOWED_VALUES = new Map<CdsFieldKey, ReadonlySet<string>>(
	(
		Object.entries(CDS_STATIC_FIELD_OPTIONS) as Array<
			[CdsFieldKey, readonly CdsStaticOption[]]
		>
	).map(([fieldKey, options]) => [
		fieldKey,
		new Set(options.map((option) => option.value.trim().toUpperCase())),
	]),
);

export function getCdsStaticFieldOptions(fieldKey: CdsFieldKey) {
	return [...(CDS_STATIC_FIELD_OPTIONS[fieldKey] ?? [])];
}

export function isCdsStaticField(fieldKey: CdsFieldKey) {
	return CDS_STATIC_FIELD_KEYS.has(fieldKey);
}

export function isAllowedCdsStaticFieldValue(
	fieldKey: CdsFieldKey,
	value: string,
) {
	const allowedValues = CDS_STATIC_ALLOWED_VALUES.get(fieldKey);

	if (!allowedValues) {
		return true;
	}

	return allowedValues.has(value.trim().toUpperCase());
}
