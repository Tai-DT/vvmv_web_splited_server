function normalizeEcusLegalDocumentText(value: string | null | undefined) {
	return (value ?? "")
		.normalize("NFD")
		.replace(/\p{Diacritic}/gu, "")
		.replace(/[^A-Za-z0-9]+/g, " ")
		.trim()
		.toUpperCase();
}

