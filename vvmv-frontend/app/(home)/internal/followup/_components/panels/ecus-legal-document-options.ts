export const ECUS_LEGAL_DOCUMENT_OPTIONS: EcusLegalDocumentOption[] =
	LEGAL_DOCUMENT_OPTIONS_SOURCE.split("\n")
		.map((line) => line.trim())
		.filter(Boolean)
		.map((line) => {
			const [value, documentNumber, issueDate] = line
				.split("|")
				.map((item) => item.trim());
			const safeValue = value.toUpperCase();
			const safeDocumentNumber = documentNumber ?? "";
			const safeIssueDate = issueDate ?? "";
			const label = `${safeValue} - ${safeDocumentNumber}`;

			return {
				value: safeValue,
				documentNumber: safeDocumentNumber,
				issueDate: safeIssueDate,
				label,
				normalized: normalizeEcusLegalDocumentText(
					`${safeValue} ${safeDocumentNumber} ${safeIssueDate}`,
				),
			};
		});

export function findEcusLegalDocumentOptionByText(
	value: string | null | undefined,
) {
	const normalized = normalizeEcusLegalDocumentText(value);
	if (!normalized) {
		return null;
	}

	return (
		ECUS_LEGAL_DOCUMENT_OPTIONS.find(
			(option) =>
				option.value === normalized || option.normalized.includes(normalized),
		) ?? null
	);
}
